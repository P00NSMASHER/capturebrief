import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {buildGeniusLab} from '../assets/genius-engine.mjs';
const read=p=>JSON.parse(readFileSync(p,'utf8'));
const yahoo=()=>read('fantasy/data.json'),edge=()=>read('fantasy/edge.json'),intel=()=>read('fantasy/intelligence.json');
const timed=()=>Date.parse(yahoo().syncedAtIso)+2*60*1000;
const run=opts=>buildGeniusLab(yahoo(),edge(),intel(),{now:timed(),field:4,realization:.5,simulations:700,...opts});
test('All-play strength uses exactly eight real Yahoo completed weeks and all eight teams',()=>{
 const g=run();
 assert.equal(g.ready,true,g.reason);
 assert.equal(g.allPlay.teams.length,8);
 assert.equal(g.allPlay.weeks.length,8);
 const b=g.allPlay.brock;
 assert.equal(b.wins,6);
 assert.equal(b.losses,2);
 assert.equal(b.allPlayMatches,56);
 assert.ok(b.allPlayPct>0&&b.allPlayPct<100);
 assert.ok(b.expectedWins>=0&&b.expectedWins<=8);
 assert.ok(b.luckWins>-8&&b.luckWins<8);
 assert.ok(g.allPlay.teams.every(t=>t.weekScores.length===8));
 assert.ok(g.allPlay.teams.every(t=>t.allPlayMatches===56));
 assert.match(g.allPlay.labels.allPlay,/seven teams/);
});
test('Walk-forward calibration is 20 held-out games and never learns from future weeks',()=>{
 const g=run();
 assert.equal(g.reliability.matchups,32);
 assert.equal(g.reliability.scoreObservations,64);
 assert.equal(g.reliability.rollingTestGames,20);
 assert.ok(g.reliability.forecastMAE>18&&g.reliability.forecastMAE<20);
 assert.ok(g.reliability.forecastRMSE>22&&g.reliability.forecastRMSE<24);
 assert.ok(g.reliability.rollingBrier>0&&g.reliability.rollingBrier<1);
 assert.ok(g.reliability.grouped.reduce((s,r)=>s+r.cases,0)===20);
 assert.match(g.reliability.method,/only earlier weeks/);
 assert.match(g.reliability.caveat,/not validated/i);
});
test('Opponent uncertainty uses paired historical Yahoo forecast errors, not arbitrary 25-point sigma',()=>{
 const g=run(),m=g.matchup;
 assert.equal(m.opponentId,'6');
 assert.equal(m.opponentName,'Josh ❤️creampies');
 assert.equal(m.week,10);
 assert.equal(m.yahooMargin,21.73);
 assert.ok(m.historicalWinScenario>0&&m.historicalWinScenario<100);
 assert.ok(m.marginBand.low<m.marginBand.high);
 assert.equal(m.opponentAllPlayPct,g.allPlay.teams.find(x=>x.teamId==='6').allPlayPct);
 assert.match(m.caveat,/not a calibrated win probability/);
});
test('Interactive playoff sensitivity responds to gain realization and 4 vs 6 fields without changing Yahoo data',()=>{
 const zero=run({realization:0}),half=run({realization:.5}),full=run({realization:1});
 assert.equal(zero.playoff.appliedWeeklyGain,0);
 assert.ok(full.playoff.appliedWeeklyGain>=half.playoff.appliedWeeklyGain);
 assert.ok(half.playoff.appliedWeeklyGain>=zero.playoff.appliedWeeklyGain);
 assert.equal(zero.playoff.delta.nextGame,0);
 assert.ok(full.playoff.scenario.week10WinPercent>=half.playoff.scenario.week10WinPercent);
 assert.ok(half.playoff.scenario.week10WinPercent>=zero.playoff.scenario.week10WinPercent);
 assert.equal(half.playoff.notes.length,5);
 assert.match(half.playoff.notes.join(' '),/Real Yahoo playoff settings were not verified/);
 const six=run({field:6});
 assert.ok(six.playoff.scenario.madeFieldPercent>=half.playoff.scenario.madeFieldPercent);
});
test('Bye coverage, waiver research and trade fit are source-verifiable with no automated acquisitions',()=>{
 const g=run();
 const gap=g.roster.byes.find(x=>x.week===13);
 assert.ok(gap.teShortage);
 assert.equal(gap.teAvailable,0);
 assert.ok(g.roster.teMarket.some(x=>x.name==='Dallas Goedert'&&x.week13Bye===false));
 const t=g.tradeCandidates.find(x=>x.give==='Woody Marks'&&x.receive==='Travis Kelce');
 assert.ok(t);
 assert.equal(t.isSupported,true);
 assert.equal(t.opponentNeed,true);
 assert.equal(t.opponentSurplus,true);
 assert.match(t.caution,/hypothetical/);
 assert.ok(!g.notes.some(x=>/submitted/i.test(x)));
});
